create table confirmation_challenges (
	id bigint generated by default as identity,
	user_action_id uuid not null references users_actions (id) on delete cascade,
	challenge_order integer not null check (challenge_order >= 0),
	encoded_confirmation_code varchar(255) not null,
	attempts integer not null,
 	completed boolean not null,
 	expires_at timestamp with time zone,
 	constraint CONFIRMATION_CHALLENGE_PK primary key (id),
 	constraint CONFIRMATION_CHALLENGE_UNIQUE_ORDER unique (user_action_id, challenge_order)
);